package com.placementiq.service;
 
import com.placementiq.dto.AtsAnalysisDto;
import com.placementiq.dto.AtsAnalysisRequest;
import com.placementiq.dto.AtsAnalysisSummaryDto;
import com.placementiq.dto.EducationDto;
import com.placementiq.dto.ExperienceDto;
import com.placementiq.dto.openai.AtsModelResult;
import com.placementiq.entity.AtsAnalysis;
import com.placementiq.entity.EducationDetail;
import com.placementiq.entity.ExperienceDetail;
import com.placementiq.entity.Resume;
import com.placementiq.entity.User;
import com.placementiq.exception.AtsAnalysisNotFoundException;
import com.placementiq.exception.ResumeNotFoundException;
import com.placementiq.repository.AtsAnalysisRepository;
import com.placementiq.repository.ResumeRepository;
import com.placementiq.repository.UserRepository;
import com.placementiq.util.AtsPromptBuilder;
import com.placementiq.validation.AtsAnalysisValidator;
import lombok.RequiredArgsConstructor;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
 
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Optional;
 
/**
 * Business logic for the ATS Resume Analysis module.
 *
 * The flow of one analysis is:
 *   1. load the authenticated user's resume (stored in Part 2)
 *   2. validate that it holds usable extracted text
 *   3. build the prompts and call OpenAiService
 *   4. sanitise and clamp everything the model returned
 *   5. persist the run and map it to a DTO
 *
 * Step 4 is not optional. The model output is untrusted input: scores can fall
 * outside 0-100, lists can be longer than the column widths allow, and entries
 * can be blank or duplicated. Sanitising here keeps invalid data out of the
 * database and out of the API response.
 *
 * As with Parts 1 and 2, every method is keyed on the user id resolved from the
 * JWT, so one student can never read or delete another student's analysis.
 */
@Service
@RequiredArgsConstructor
public class AtsAnalysisService {
 
    private static final Logger log = LoggerFactory.getLogger(AtsAnalysisService.class);
 
    /**
     * Shown beside every score in the API response and on the React page, so the
     * number is never mistaken for a real employer ATS result.
     */
    public static final String SCORE_DISCLAIMER =
            "This score is generated by PlacementIQ using an AI language model. "
                    + "It is an indicative guide for improving your resume and is not the score "
                    + "produced by any real employer's Applicant Tracking System.";
 
    // Caps that match the column widths declared on the AtsAnalysis entity.
    private static final int MAX_LIST_ITEMS = 40;
    private static final int MAX_SHORT_ITEM_LENGTH = 120;
    private static final int MAX_SUGGESTION_LENGTH = 500;
    private static final int MAX_DETAIL_ENTRIES = 15;
 
    private final AtsAnalysisRepository atsAnalysisRepository;
    private final ResumeRepository resumeRepository;
    private final UserRepository userRepository;
    private final AtsAnalysisValidator validator;
    private final AtsPromptBuilder promptBuilder;
    private final OpenAiService openAiService;
 
    /**
     * Runs a fresh analysis of the authenticated user's stored resume and saves
     * the result as a new history row.
     */
    @Transactional
    public AtsAnalysisDto analyzeResume(Long userId, AtsAnalysisRequest request) {
        Resume resume = resumeRepository.findByUserId(userId)
                .orElseThrow(() -> new ResumeNotFoundException(
                        "No resume found for this account. Please upload a resume before running an ATS analysis."));
 
        validator.validateForAnalysis(resume);
 
        String targetRole = validator.normalizeTargetRole(
                request == null ? null : request.getTargetRole());
 
        User user = userRepository.findById(userId)
                .orElseThrow(() -> new ResumeNotFoundException("User not found with id: " + userId));
 
        String systemPrompt = promptBuilder.buildSystemPrompt();
        String userPrompt = promptBuilder.buildUserPrompt(resume.getExtractedText(), targetRole);
 
        long startedAt = System.currentTimeMillis();
        AtsModelResult result = openAiService.completeAsJson(systemPrompt, userPrompt, AtsModelResult.class);
        long elapsedMs = System.currentTimeMillis() - startedAt;
 
        log.info("ATS analysis completed for user {} in {} ms", userId, elapsedMs);
 
        AtsAnalysis analysis = AtsAnalysis.builder()
                .user(user)
                .resume(resume)
                .resumeFileName(resume.getOriginalFileName())
                .targetRole(targetRole)
                .overallScore(clampScore(result.getOverallScore()))
                .skillsScore(clampScore(result.getSkillsScore()))
                .keywordScore(clampScore(result.getKeywordScore()))
                .formattingScore(clampScore(result.getFormattingScore()))
                .completenessScore(clampScore(result.getCompletenessScore()))
                .skills(sanitizeList(result.getSkills(), MAX_SHORT_ITEM_LENGTH))
                .keywords(sanitizeList(result.getKeywords(), MAX_SHORT_ITEM_LENGTH))
                .missingKeywords(sanitizeList(result.getMissingKeywords(), MAX_SHORT_ITEM_LENGTH))
                .suggestions(sanitizeList(result.getSuggestions(), MAX_SUGGESTION_LENGTH))
                .missingSections(sanitizeList(result.getMissingSections(), MAX_SHORT_ITEM_LENGTH))
                .education(toEducationDetails(result.getEducation()))
                .experience(toExperienceDetails(result.getExperience()))
                .totalExperienceYears(clampYears(result.getTotalExperienceYears()))
                .summary(truncate(result.getSummary(), 2000))
                .modelUsed(openAiService.getConfiguredModel())
                .processingTimeMs(elapsedMs)
                .build();
 
        AtsAnalysis saved = atsAnalysisRepository.save(analysis);
        return toDto(saved);
    }
 
    /**
     * @return the most recent analysis, or an empty Optional when the user has
     *         never run one. Returning Optional rather than throwing lets the
     *         controller answer 200 with null data, which is what the React page
     *         needs to distinguish "no analysis yet" from an error.
     */
    @Transactional(readOnly = true)
    public Optional<AtsAnalysisDto> getLatestAnalysis(Long userId) {
        return atsAnalysisRepository.findFirstByUserIdOrderByAnalyzedAtDesc(userId)
                .map(this::toDto);
    }
 
    @Transactional(readOnly = true)
    public AtsAnalysisDto getAnalysis(Long userId, Long analysisId) {
        AtsAnalysis analysis = atsAnalysisRepository.findByIdAndUserId(analysisId, userId)
                .orElseThrow(() -> new AtsAnalysisNotFoundException(
                        "No ATS analysis found with id " + analysisId + " for this account."));
        return toDto(analysis);
    }
 
    @Transactional(readOnly = true)
    public List<AtsAnalysisSummaryDto> getAnalysisHistory(Long userId) {
        return atsAnalysisRepository.findByUserIdOrderByAnalyzedAtDesc(userId).stream()
                .map(this::toSummaryDto)
                .toList();
    }
 
    @Transactional
    public void deleteAnalysis(Long userId, Long analysisId) {
        AtsAnalysis analysis = atsAnalysisRepository.findByIdAndUserId(analysisId, userId)
                .orElseThrow(() -> new AtsAnalysisNotFoundException(
                        "No ATS analysis found with id " + analysisId + " for this account."));
        atsAnalysisRepository.delete(analysis);
    }
 
    /** Backs the readiness endpoint the React page calls before enabling the button. */
    @Transactional(readOnly = true)
    public boolean canAnalyze(Long userId) {
        return resumeRepository.findByUserId(userId)
                .map(resume -> resume.getExtractedText() != null
                        && !resume.getExtractedText().isBlank())
                .orElse(false);
    }
 
    public boolean isAiConfigured() {
        return openAiService.isAvailable();
    }
 
    // ------------------------------------------------------------------
    // Sanitising the model output
    // ------------------------------------------------------------------
 
    /** Forces any score into 0-100; a missing score becomes 0. */
    private int clampScore(Integer raw) {
        if (raw == null) {
            return 0;
        }
        return Math.max(0, Math.min(100, raw));
    }
 
    /** Rejects negative or implausible experience totals. */
    private Double clampYears(Double raw) {
        if (raw == null || raw.isNaN() || raw < 0) {
            return 0.0;
        }
        return Math.min(raw, 60.0);
    }
 
    /**
     * Trims, drops blanks, removes duplicates case-insensitively while keeping
     * the model's ordering, truncates each entry to the column width and caps
     * the list length.
     */
    private List<String> sanitizeList(List<String> raw, int maxItemLength) {
        List<String> cleaned = new ArrayList<>();
        if (raw == null) {
            return cleaned;
        }
        LinkedHashSet<String> seen = new LinkedHashSet<>();
        for (String item : raw) {
            if (item == null) {
                continue;
            }
            String value = item.trim().replaceAll("\\s+", " ");
            if (value.isEmpty()) {
                continue;
            }
            if (value.length() > maxItemLength) {
                value = value.substring(0, maxItemLength);
            }
            if (seen.add(value.toLowerCase())) {
                cleaned.add(value);
            }
            if (cleaned.size() >= MAX_LIST_ITEMS) {
                break;
            }
        }
        return cleaned;
    }
 
    private List<EducationDetail> toEducationDetails(List<AtsModelResult.Education> raw) {
        List<EducationDetail> details = new ArrayList<>();
        if (raw == null) {
            return details;
        }
        for (AtsModelResult.Education entry : raw) {
            if (entry == null) {
                continue;
            }
            EducationDetail detail = EducationDetail.builder()
                    .degree(truncate(entry.getDegree(), 200))
                    .institution(truncate(entry.getInstitution(), 200))
                    .year(truncate(entry.getYear(), 60))
                    .score(truncate(entry.getScore(), 60))
                    .build();
            if (hasAnyValue(detail.getDegree(), detail.getInstitution(), detail.getYear(), detail.getScore())) {
                details.add(detail);
            }
            if (details.size() >= MAX_DETAIL_ENTRIES) {
                break;
            }
        }
        return details;
    }
 
    private List<ExperienceDetail> toExperienceDetails(List<AtsModelResult.Experience> raw) {
        List<ExperienceDetail> details = new ArrayList<>();
        if (raw == null) {
            return details;
        }
        for (AtsModelResult.Experience entry : raw) {
            if (entry == null) {
                continue;
            }
            ExperienceDetail detail = ExperienceDetail.builder()
                    .jobTitle(truncate(entry.getJobTitle(), 200))
                    .organization(truncate(entry.getOrganization(), 200))
                    .duration(truncate(entry.getDuration(), 120))
                    .description(truncate(entry.getDescription(), 1000))
                    .build();
            if (hasAnyValue(detail.getJobTitle(), detail.getOrganization(),
                    detail.getDuration(), detail.getDescription())) {
                details.add(detail);
            }
            if (details.size() >= MAX_DETAIL_ENTRIES) {
                break;
            }
        }
        return details;
    }
 
    private boolean hasAnyValue(String... values) {
        for (String value : values) {
            if (value != null && !value.isBlank()) {
                return true;
            }
        }
        return false;
    }
 
    private String truncate(String value, int maxLength) {
        if (value == null) {
            return null;
        }
        String trimmed = value.trim();
        if (trimmed.isEmpty()) {
            return null;
        }
        return trimmed.length() > maxLength ? trimmed.substring(0, maxLength) : trimmed;
    }
 
    // ------------------------------------------------------------------
    // Mapping
    // ------------------------------------------------------------------
 
    /** Turns a 0-100 score into the label shown next to the gauge. */
    private String scoreBand(Integer score) {
        int value = score == null ? 0 : score;
        if (value >= 85) return "Excellent";
        if (value >= 70) return "Good";
        if (value >= 55) return "Fair";
        if (value >= 40) return "Needs Work";
        return "Poor";
    }
 
    private AtsAnalysisDto toDto(AtsAnalysis analysis) {
        return AtsAnalysisDto.builder()
                .id(analysis.getId())
                .resumeId(analysis.getResume() == null ? null : analysis.getResume().getId())
                .resumeFileName(analysis.getResumeFileName())
                .targetRole(analysis.getTargetRole())
                .overallScore(analysis.getOverallScore())
                .skillsScore(analysis.getSkillsScore())
                .keywordScore(analysis.getKeywordScore())
                .formattingScore(analysis.getFormattingScore())
                .completenessScore(analysis.getCompletenessScore())
                .scoreBand(scoreBand(analysis.getOverallScore()))
                .scoreDisclaimer(SCORE_DISCLAIMER)
                .skills(analysis.getSkills())
                .keywords(analysis.getKeywords())
                .missingKeywords(analysis.getMissingKeywords())
                .suggestions(analysis.getSuggestions())
                .missingSections(analysis.getMissingSections())
                .education(analysis.getEducation().stream()
                        .map(e -> EducationDto.builder()
                                .degree(e.getDegree())
                                .institution(e.getInstitution())
                                .year(e.getYear())
                                .score(e.getScore())
                                .build())
                        .toList())
                .experience(analysis.getExperience().stream()
                        .map(e -> ExperienceDto.builder()
                                .jobTitle(e.getJobTitle())
                                .organization(e.getOrganization())
                                .duration(e.getDuration())
                                .description(e.getDescription())
                                .build())
                        .toList())
                .totalExperienceYears(analysis.getTotalExperienceYears())
                .summary(analysis.getSummary())
                .modelUsed(analysis.getModelUsed())
                .processingTimeMs(analysis.getProcessingTimeMs())
                .analyzedAt(analysis.getAnalyzedAt())
                .build();
    }
 
    private AtsAnalysisSummaryDto toSummaryDto(AtsAnalysis analysis) {
        return AtsAnalysisSummaryDto.builder()
                .id(analysis.getId())
                .resumeFileName(analysis.getResumeFileName())
                .targetRole(analysis.getTargetRole())
                .overallScore(analysis.getOverallScore())
                .scoreBand(scoreBand(analysis.getOverallScore()))
                .skillCount(analysis.getSkills().size())
                .missingKeywordCount(analysis.getMissingKeywords().size())
                .analyzedAt(analysis.getAnalyzedAt())
                .build();
    }
}
