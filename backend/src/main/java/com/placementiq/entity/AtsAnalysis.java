package com.placementiq.entity;
 
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
 
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;
 
/**
 * One completed ATS-style analysis of a user's stored resume.
 *
 * Every run is persisted as a new row rather than overwriting the previous one,
 * so a student can see how their resume improved after each edit. The most
 * recent row is what the React page shows by default.
 *
 * Note on @OrderColumn: each collection below is declared as an indexed list
 * rather than a plain bag. This preserves the order the analysis produced (which
 * matters for the suggestion list) and, just as importantly, avoids Hibernate's
 * MultipleBagFetchException, which is raised at start-up when one entity holds
 * several eagerly fetched bag collections.
 *
 * IMPORTANT: every score on this entity is generated by PlacementIQ using a
 * language model. It is an indicative, application-generated score meant to
 * guide improvements - it is NOT the score any real employer's Applicant
 * Tracking System would produce, and must never be presented as such.
 */
@Entity
@Table(name = "ats_analyses", indexes = {
        @Index(name = "idx_ats_analyses_user_id", columnList = "user_id"),
        @Index(name = "idx_ats_analyses_resume_id", columnList = "resume_id")
})
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class AtsAnalysis {
 
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;
 
    /** Owner of the analysis. Many analyses may exist per user (one per run). */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;
 
    /** The resume that was analysed. */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "resume_id", nullable = false)
    private Resume resume;
 
    /**
     * Snapshot of the resume file name at the time of the run, so a historical
     * analysis still makes sense after the resume has been replaced.
     */
    @Column(name = "resume_file_name", nullable = false, length = 255)
    private String resumeFileName;
 
    /** Optional role the student was targeting, used to tailor the analysis. */
    @Column(name = "target_role", length = 150)
    private String targetRole;
 
    // ------------------------------------------------------------------
    // Scores - all application-generated, all clamped to 0..100
    // ------------------------------------------------------------------
 
    @Column(name = "overall_score", nullable = false)
    private Integer overallScore;
 
    @Column(name = "skills_score")
    private Integer skillsScore;
 
    @Column(name = "keyword_score")
    private Integer keywordScore;
 
    @Column(name = "formatting_score")
    private Integer formattingScore;
 
    @Column(name = "completeness_score")
    private Integer completenessScore;
 
    // ------------------------------------------------------------------
    // Extracted content
    // ------------------------------------------------------------------
 
    /** Technical and soft skills found in the resume. */
    @ElementCollection(fetch = FetchType.EAGER)
    @CollectionTable(name = "ats_analysis_skills",
            joinColumns = @JoinColumn(name = "analysis_id"))
    @Column(name = "skill", length = 120)
    @OrderColumn(name = "item_order")
    @Builder.Default
    private List<String> skills = new ArrayList<>();
 
    /** ATS-relevant keywords that are present in the resume. */
    @ElementCollection(fetch = FetchType.EAGER)
    @CollectionTable(name = "ats_analysis_keywords",
            joinColumns = @JoinColumn(name = "analysis_id"))
    @Column(name = "keyword", length = 120)
    @OrderColumn(name = "item_order")
    @Builder.Default
    private List<String> keywords = new ArrayList<>();
 
    /** Keywords a recruiter would expect but which are absent from the resume. */
    @ElementCollection(fetch = FetchType.EAGER)
    @CollectionTable(name = "ats_analysis_missing_keywords",
            joinColumns = @JoinColumn(name = "analysis_id"))
    @Column(name = "keyword", length = 120)
    @OrderColumn(name = "item_order")
    @Builder.Default
    private List<String> missingKeywords = new ArrayList<>();
 
    /** Actionable, ATS-oriented improvement suggestions. */
    @ElementCollection(fetch = FetchType.EAGER)
    @CollectionTable(name = "ats_analysis_suggestions",
            joinColumns = @JoinColumn(name = "analysis_id"))
    @Column(name = "suggestion", length = 500)
    @OrderColumn(name = "item_order")
    @Builder.Default
    private List<String> suggestions = new ArrayList<>();
 
    /** Standard resume sections that appear to be missing entirely. */
    @ElementCollection(fetch = FetchType.EAGER)
    @CollectionTable(name = "ats_analysis_missing_sections",
            joinColumns = @JoinColumn(name = "analysis_id"))
    @Column(name = "section", length = 120)
    @OrderColumn(name = "item_order")
    @Builder.Default
    private List<String> missingSections = new ArrayList<>();
 
    @ElementCollection(fetch = FetchType.EAGER)
    @CollectionTable(name = "ats_analysis_education",
            joinColumns = @JoinColumn(name = "analysis_id"))
    @OrderColumn(name = "item_order")
    @Builder.Default
    private List<EducationDetail> education = new ArrayList<>();
 
    @ElementCollection(fetch = FetchType.EAGER)
    @CollectionTable(name = "ats_analysis_experience",
            joinColumns = @JoinColumn(name = "analysis_id"))
    @OrderColumn(name = "item_order")
    @Builder.Default
    private List<ExperienceDetail> experience = new ArrayList<>();
 
    /** Short plain-language verdict shown at the top of the result page. */
    @Column(name = "summary", columnDefinition = "TEXT")
    private String summary;
 
    /** Total years of experience the model inferred from the resume. */
    @Column(name = "total_experience_years")
    private Double totalExperienceYears;
 
    // ------------------------------------------------------------------
    // Provenance
    // ------------------------------------------------------------------
 
    /** OpenAI model that produced this analysis, e.g. "gpt-4o-mini". */
    @Column(name = "model_used", length = 80)
    private String modelUsed;
 
    /** Wall-clock duration of the OpenAI call, useful for the project report. */
    @Column(name = "processing_time_ms")
    private Long processingTimeMs;
 
    @Column(name = "analyzed_at", nullable = false, updatable = false)
    private LocalDateTime analyzedAt;
 
    @PrePersist
    protected void onCreate() {
        this.analyzedAt = LocalDateTime.now();
    }
}
