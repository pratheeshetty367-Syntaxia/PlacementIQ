package com.placementiq.dto;
 
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
 
import java.time.LocalDateTime;
import java.util.List;
 
/**
 * The full ATS analysis returned to the React page.
 *
 * The scoreDisclaimer field is always populated by the service and is rendered
 * next to the score on the frontend, so the number is never presented as a
 * real employer ATS result.
 */
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class AtsAnalysisDto {
 
    private Long id;
    private Long resumeId;
    private String resumeFileName;
    private String targetRole;
 
    // Application-generated scores, 0-100
    private Integer overallScore;
    private Integer skillsScore;
    private Integer keywordScore;
    private Integer formattingScore;
    private Integer completenessScore;
 
    /** Human-readable band derived from overallScore, e.g. "Good". */
    private String scoreBand;
 
    /** Always set; states that the score is generated by PlacementIQ. */
    private String scoreDisclaimer;
 
    private List<String> skills;
    private List<String> keywords;
    private List<String> missingKeywords;
    private List<String> suggestions;
    private List<String> missingSections;
 
    private List<EducationDto> education;
    private List<ExperienceDto> experience;
 
    private Double totalExperienceYears;
    private String summary;
 
    private String modelUsed;
    private Long processingTimeMs;
    private LocalDateTime analyzedAt;
}
